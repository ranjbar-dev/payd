import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const source = await readFile(resolve(root, "backend/internal/api/openapi.yaml"), "utf8");
const paths = source.slice(source.indexOf("paths:"), source.indexOf("\ncomponents:"));
// Unauthenticated payd routes. They require no X-API-Key and are not rate limited,
// but they still pass through the proxy because the browser cannot reach payd
// directly (BFF-001, OPS-009).
const PUBLIC_ROUTES = new Set(["/healthz", "/readyz", "/openapi.yaml"]);
let current = "";
const routes = [];

for (const line of paths.split(/\r?\n/)) {
  const path = line.match(/^  (\/[^:]+):\s*$/);
  if (path) {
    current = path[1];
    continue;
  }
  const method = line.match(/^    (get|post):\s*$/);
  if (!method) continue;
  // The proxy is the browser's only route to payd (BFF-001), so the allowlist must
  // cover the unauthenticated routes too. /readyz in particular backs the Overview
  // readiness card (WOVW-010/011); filtering to /api/v1/ silently dropped it and the
  // proxy 404'd a route the specification requires.
  if (current.startsWith("/api/v1/")) {
    routes.push({ method: method[1].toUpperCase(), path: current.slice("/api/v1/".length) });
  } else if (PUBLIC_ROUTES.has(current)) {
    routes.push({ method: method[1].toUpperCase(), path: current.slice(1), public: true });
  }
}

if (routes.length === 0) throw new Error("No /api/v1 routes found in backend OpenAPI");
for (const expected of PUBLIC_ROUTES) {
  if (!routes.some((route) => `/${route.path}` === expected)) {
    throw new Error(`Public route ${expected} is missing from the generated allowlist`);
  }
}

const output = `import 'server-only';

// Generated by scripts/generate-payd-allowlist.mjs from backend/internal/api/openapi.yaml.
// Do not edit by hand; run \`node scripts/generate-payd-allowlist.mjs\`.
export type PaydRoute = { readonly method: string; readonly path: string; readonly public?: boolean };

export const paydRoutes: readonly PaydRoute[] = ${JSON.stringify(routes, null, 2)} as const;

export function findAllowedRoute(method: string, path: string[]): PaydRoute | undefined {
  return paydRoutes.find((route) => {
    const parts = route.path.split('/');
    if (route.method !== method || parts.length !== path.length) return false;
    return parts.every((part, index) => part.startsWith('{') && part.endsWith('}') ? path[index] !== '' : part === path[index]);
  });
}

export function matchAllowedRoute(method: string, path: string[]): boolean {
  return findAllowedRoute(method, path) !== undefined;
}

// Public payd routes are served at the root, not under /api/v1, and take no key.
export function upstreamPath(route: PaydRoute, path: string[]): string {
  const joined = path.map(encodeURIComponent).join('/');
  return route.public ? \`/\${joined}\` : \`/api/v1/\${joined}\`;
}
`;
await writeFile(resolve(root, "web/lib/payd/allowlist.ts"), output);
